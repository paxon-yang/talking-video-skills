#!/usr/bin/env python3
"""hom_to_css.py - 把 plane_track.py 输出的单应矩阵（plate 局部 px → 屏幕 px）转成 CSS matrix3d 字符串 / TS 表。
CSS 要求：元素 transform-origin 设为 '0 0'（局部左上角），且元素放在屏幕坐标系原点（左上角）处，perspective 不用设（矩阵已含透视）。
matrix3d 的 16 个数（列主序）：matrix3d(h00,h10,0,h20, h01,h11,0,h21, 0,0,1,0, h02,h12,0,h22)，H 行主序 [[h00,h01,h02],[h10,h11,h12],[h20,h21,h22]]。

用法：
  python3 hom_to_css.py track.txt                 # 每帧打印一行 'f: matrix3d(...)'
  python3 hom_to_css.py track.txt --ts out.ts     # 写成 export const PANEL_H: Record<number, number[]> = { f: [h00..h22], ... }
  python3 hom_to_css.py track.txt --canvas-scale 1.0   # 原片分辨率与合成分辨率不同时，H 左乘缩放矩阵
Remotion 里用法：<div style={{position:'absolute',left:0,top:0,width:w,height:h,transformOrigin:'0 0',transform:matrix3d(...)}}>。
FAIL 行跳过。依赖：numpy。
"""
import argparse, numpy as np

ap = argparse.ArgumentParser(); ap.add_argument('track'); ap.add_argument('--ts'); ap.add_argument('--canvas-scale', type=float, default=1.0)
a = ap.parse_args()
res = {}
for l in open(a.track):
    t = l.split()
    if len(t) < 12 or t[1] == 'FAIL':
        continue
    H = np.array(list(map(float, t[3:12]))).reshape(3, 3)
    H = np.diag([a.canvas_scale, a.canvas_scale, 1.0]) @ H
    res[int(t[0])] = H / H[2, 2]
css = lambda H: 'matrix3d(%s)' % ','.join(f'{v:.7g}' for v in [H[0, 0], H[1, 0], 0, H[2, 0], H[0, 1], H[1, 1], 0, H[2, 1], 0, 0, 1, 0, H[0, 2], H[1, 2], 0, H[2, 2]])
if a.ts:
    with open(a.ts, 'w') as fh:
        fh.write('// generated by hom_to_css.py: per-frame homography, plate-local px -> screen px, row-major h00..h22\n')
        fh.write('export const PANEL_H: Record<number, number[]> = {\n')
        for f in sorted(res):
            fh.write(f'  {f}: [' + ', '.join(f'{v:.7g}' for v in res[f].ravel()) + '],\n')
        fh.write('};\n')
    print('wrote', a.ts, len(res), 'frames')
else:
    for f in sorted(res):
        print(f'{f}: {css(res[f])}')
